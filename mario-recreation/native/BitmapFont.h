#pragma once
#include <SDL.h>
#include <array>
#include <string>
#include <unordered_map>
// Unfiltered 8x8 bitmap cells; avoids TrueType scaling and fractional glyph edges.
inline void drawBitmapText(SDL_Renderer* renderer, const std::string& text, int x, int y, int cell) {
   static const std::unordered_map<char, std::array<Uint8,8>> glyphs = {
      {'0',{0x7c,0xc6,0xce,0xde,0xf6,0xe6,0x7c,0}},
      {'1',{0x18,0x38,0x18,0x18,0x18,0x18,0x7e,0}},
      {'2',{0x7c,0xc6,0x06,0x1c,0x70,0xc0,0xfe,0}},
      {'3',{0x7c,0xc6,0x06,0x3c,0x06,0xc6,0x7c,0}},
      {'4',{0x1c,0x3c,0x6c,0xcc,0xfe,0x0c,0x0c,0}},
      {'5',{0xfe,0xc0,0xfc,0x06,0x06,0xc6,0x7c,0}},
      {'6',{0x3c,0x60,0xc0,0xfc,0xc6,0xc6,0x7c,0}},
      {'7',{0xfe,0xc6,0x0c,0x18,0x30,0x30,0x30,0}},
      {'8',{0x7c,0xc6,0xc6,0x7c,0xc6,0xc6,0x7c,0}},
      {'9',{0x7c,0xc6,0xc6,0x7e,0x06,0x0c,0x78,0}},
      {'A',{0x38,0x6c,0xc6,0xc6,0xfe,0xc6,0xc6,0}},
      {'B',{0xfc,0xc6,0xc6,0xfc,0xc6,0xc6,0xfc,0}},
      {'C',{0x7c,0xc6,0xc0,0xc0,0xc0,0xc6,0x7c,0}},
      {'D',{0xf8,0xcc,0xc6,0xc6,0xc6,0xcc,0xf8,0}},
      {'E',{0xfe,0xc0,0xc0,0xfc,0xc0,0xc0,0xfe,0}},
      {'F',{0xfe,0xc0,0xc0,0xfc,0xc0,0xc0,0xc0,0}},
      {'G',{0x7c,0xc6,0xc0,0xce,0xc6,0xc6,0x7e,0}},
      {'H',{0xc6,0xc6,0xc6,0xfe,0xc6,0xc6,0xc6,0}},
      {'I',{0x7e,0x18,0x18,0x18,0x18,0x18,0x7e,0}},
      {'J',{0x1e,0x06,0x06,0x06,0xc6,0xc6,0x7c,0}},
      {'K',{0xc6,0xcc,0xd8,0xf0,0xd8,0xcc,0xc6,0}},
      {'L',{0xc0,0xc0,0xc0,0xc0,0xc0,0xc0,0xfe,0}},
      {'M',{0xc6,0xee,0xfe,0xfe,0xd6,0xc6,0xc6,0}},
      {'N',{0xc6,0xe6,0xf6,0xde,0xce,0xc6,0xc6,0}},
      {'O',{0x7c,0xc6,0xc6,0xc6,0xc6,0xc6,0x7c,0}},
      {'P',{0xfc,0xc6,0xc6,0xfc,0xc0,0xc0,0xc0,0}},
      {'Q',{0x7c,0xc6,0xc6,0xc6,0xd6,0xcc,0x7a,0}},
      {'R',{0xfc,0xc6,0xc6,0xfc,0xd8,0xcc,0xc6,0}},
      {'S',{0x7c,0xc6,0xc0,0x7c,0x06,0xc6,0x7c,0}},
      {'T',{0x7e,0x18,0x18,0x18,0x18,0x18,0x18,0}},
      {'U',{0xc6,0xc6,0xc6,0xc6,0xc6,0xc6,0x7c,0}},
      {'V',{0xc6,0xc6,0xc6,0xc6,0xc6,0x6c,0x38,0}},
      {'W',{0xc6,0xc6,0xc6,0xd6,0xfe,0xee,0xc6,0}},
      {'X',{0xc6,0xc6,0x6c,0x38,0x6c,0xc6,0xc6,0}},
      {'Y',{0x66,0x66,0x66,0x3c,0x18,0x18,0x18,0}},
      {'Z',{0xfe,0x06,0x0c,0x18,0x30,0x60,0xfe,0}},
      {'-',{0,0,0,0x7e,0,0,0,0}},
      {'x',{0,0,0x66,0x3c,0x18,0x3c,0x66,0}},
      {'!',{0x18,0x3c,0x3c,0x18,0x18,0,0x18,0}},
      {'.',{0,0,0,0,0,0x18,0x18,0}},
      {'>',{0x60,0x30,0x18,0x0c,0x18,0x30,0x60,0}},
   };
   SDL_SetRenderDrawColor(renderer, 255,255,255,255);
   for (char c : text) {
      auto it = glyphs.find(c);
      if (it != glyphs.end()) for (int row=0; row<8; ++row) for (int col=0; col<8; ++col) {
         if (!(it->second[row] & (0x80 >> col))) continue;
         SDL_Rect pixel{x+col*cell/8, y+row*cell/8, (col+1)*cell/8-col*cell/8, (row+1)*cell/8-row*cell/8};
         SDL_RenderFillRect(renderer, &pixel);
      }
      x += cell;
   }
}
